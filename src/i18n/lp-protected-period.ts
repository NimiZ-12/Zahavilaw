/* ----------------------------------------------------------------------------
   Content for the "protected period" campaign landing page (/he/lp/protected-period).
   ---------------------------------------------------------------------------
   Why this lives here and not in the he/en dictionaries:

   The dictionaries describe the site itself, and their shared `Dictionary` type
   forces every string to exist in both locales. This page is a Hebrew-only
   campaign destination for a Hebrew YouTube video - there is no English
   audience for it, and an English translation would have to be kept in sync
   forever for a page nobody would read. Publishing an English URL we do not
   intend to maintain would also make the hreflang pair point at a page with no
   real content, which hurts rather than helps.

   So the route is built for `he` only (see the page's generateStaticParams),
   carries a self-canonical with no hreflang alternates, and keeps its copy in
   this typed module. The rule the guidelines are protecting - no hardcoded
   strings inside components - still holds: the page component below renders
   nothing but what this file provides.

   Every statement here was checked against the statute before it was written.
   The sources are named in `cite` so a future edit can re-verify them.
---------------------------------------------------------------------------- */

